A(("h3", "1.3.3　基于深度学习的方法"))
A(("p", "2015 年以后，以卷积神经网络为代表的深度学习方法开始主导示功图识别研究。与手工特征不同，CNN 可以直接以图像或曲线作为输入，"
        "通过多层卷积自动学习从边缘、局部形态到整体轮廓的层次化表示，避免了繁重的特征设计工作。"
        "相关研究大致可分为几条技术路线：一是直接把示功图转成图像后用 CNN 分类，并结合迁移学习解决样本不足的问题；"
        "二是把载荷—位移序列看作一维时序信号，用 LSTM、TCN 或一维卷积建模；三是把示功图与电流、压力、产量等多源数据融合，"
        "用 CNN-XGBoost 等混合模型提升识别率；四是引入主动学习、半监督学习与生成对抗网络，降低标注成本、缓解类别不均衡。"
        "李汉周等提出的深度主动学习示功图诊断方法，通过不确定性采样挑选最有价值的样本进行标注，在保证精度的同时大幅减少了人工标注量[5]。"))

