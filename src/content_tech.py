A(("h1", "2　相关技术"))

A(("h2", "2.1　任务定义与总体方案"))
A(("p", "本文将示功图诊断建模为单标签图像分类问题：给定一张示功图图像 x（统一为 96×96 灰度图），模型需要输出它属于 10 个工况类别中"
        "每一类的概率 p(y=k|x)，并取概率最大的类别作为预测结果。训练集用于学习参数，验证集用于选择最佳轮次与调整超参数，"
        "测试集只在全部训练与调参结束后使用一次，以保证评估结果的客观性。"))
A(("p", "整体方案包括四个环节：数据预处理与增强、模型构建、训练与调优、评估与分析。为了客观评价深度模型的效果，本文还搭建了三类对照方法："
        "基于手工特征的 SVM、基于像素的 PCA+SVM，以及更深的 ResNet18；并从精度、参数量、训练与推理耗时、抗扰动能力四个维度进行比较。"))

A(("h2", "2.2　数据预处理与增强"))
A(("p", "原始示功图为 224×224 的 RGB 图像，内容为白底黑线的闭合轮廓，颜色信息几乎为零。为降低计算量并去除冗余通道，"
        "预处理时统一转为灰度图，再用双线性插值缩放到 96×96。实验表明，96×96 已经足以保留示功图的形态细节，"
        "而像素数只有原来的 18%，在 CPU 上训练速度提升明显。缩放后按均值 0.88、标准差 0.18 做标准化，使输入分布接近零均值，"
        "有利于卷积层的稳定训练。"))
A(("p", "数据增强是提高小样本与不均衡数据泛化能力的常用手段。本文对训练样本做随机仿射变换：旋转 ±5°、平移不超过图像尺寸的 5%、"
        "随机缩放 0.9~1.1 倍，变换后空出的区域用白色（255）填充，与原始图像的背景一致。这样既模拟了现场测量中光杆轻微偏斜、"
        "传感器安装位置差异带来的形态变化，又不会破坏示功图的整体拓扑结构。验证集与测试集不做任何增强，只做缩放与标准化，"
        "以保证评估的一致性。"))

A(("h2", "2.3　卷积神经网络"))
A(("h3", "2.3.1　卷积与感受野"))
A(("p", "卷积层是 CNN 的核心[6]。一个大小为 3×3 的卷积核在输入特征图上滑动，对每个位置做加权求和，得到新的特征图。"
        "与全连接层相比，卷积具有局部连接与权值共享两个特性：局部连接使网络只关注邻域内的纹理与边缘，符合图像的空间相关性；"
        "权值共享使同一卷积核在整幅图上检测同一种模式，参数量与图像尺寸无关。随着层数加深，深层神经元的感受野不断增大，"
        "能够从边缘、角点逐步组合出局部形态乃至完整的示功图轮廓。"))
A(("p", "本文的 SGTNet-S 由 4 个卷积块串联而成，每个卷积块包含 1~2 个 3×3 卷积、批归一化与 ReLU 激活，末端接 2×2 最大池化，"
        "特征图尺寸依次为 48×48、24×24、12×12、6×6，通道数依次为 24、48、96、120。最后用全局平均池化把 6×6×120 的特征图压缩为 120 维向量，"
        "经 Dropout 后由全连接层输出 10 类得分。整个网络只有约 0.26 M 参数，模型文件约 1 MB，便于部署到边缘设备。"))

A(("h3", "2.3.2　批归一化与激活函数"))
A(("p", "批归一化（Batch Normalization）在每个小批量上对卷积输出做标准化，再通过可学习的缩放与平移恢复表达能力[7]。"
        "它可以缓解内部协变量偏移，允许使用较大的学习率，并起到一定的正则化作用。激活函数选用 ReLU，"
        "其单侧抑制特性使网络具有稀疏激活的能力，同时计算简单、梯度不易饱和，是深层 CNN 的默认选择。"))

A(("h3", "2.3.3　全局平均池化与分类头"))
A(("p", "传统 CNN 在卷积层之后接多层全连接，参数量大且容易过拟合。本文采用全局平均池化（GAP）代替展平操作："
        "对每个通道的特征图取平均，得到与通道数等长的向量。GAP 把参数量从“通道数×空间尺寸×类别数”降到“通道数×类别数”，"
        "同时保留了通道级的语义信息，使模型对输入的空间平移更加鲁棒。分类头只保留一层全连接，配合 Dropout(0.1) 抑制过拟合。"))

A(("h2", "2.4　损失函数与优化策略"))
A(("h3", "2.4.1　类别加权交叉熵"))
A(("p", "本数据集类别分布很不均衡：最多的 A02 类有 5492 张训练图，最少的 A04 类只有 203 张，相差 27 倍。"
        "若直接使用普通交叉熵，模型会倾向于把样本判给多数类，导致少数类召回率偏低。为此本文采用类别加权交叉熵："
        "第 c 类的权重取 w_c = N /(C·N_c)，其中 N 为训练样本总数、N_c 为该类样本数、C 为类别数。"
        "这样少数类的损失被放大，模型在优化时会更加关注它们。"))
A(("h3", "2.4.2　标签平滑"))
A(("p", "one-hot 标签要求模型把正确类别的概率推向 1、其余类别推向 0，在噪声样本或类别边界模糊时容易导致过度自信。"
        "标签平滑把目标分布由 (0,…,1,…,0) 改为 (ε/C, …, 1-ε+ε/C, …, ε/C)，本文取 ε=0.05[8]。"
        "它相当于在损失中加入了正则项，可以抑制模型对训练集的过拟合，改善置信度校准，对示功图这种类间形态相近的任务尤为有益。"))
A(("h3", "2.4.3　AdamW 与余弦退火"))
A(("p", "优化器选用 AdamW，它在 Adam[9] 的自适应学习率基础上把权重衰减与梯度更新解耦，正则效果更稳定[10]。初始学习率 1e-3，"
        "权重衰减 1e-4。学习率调度采用余弦退火：学习率按余弦曲线从初始值平滑衰减到接近 0，前期快速下降、后期精细调整，"
        "有利于模型收敛到更平坦的极小值。批大小设为 128，共训练 12 轮。"))

A(("h2", "2.5　评价指标"))
A(("p", "分类任务常用准确率（Accuracy）衡量整体正确率，但在类别不均衡时它会掩盖少数类的表现，因此本文同时报告宏平均 F1（Macro-F1）："
        "先分别计算每一类的精确率 P_c 与召回率 R_c，得到 F1_c = 2P_cR_c/(P_c+R_c)，再对 10 类取算术平均。"
        "宏平均对每个类别一视同仁，能更敏感地反映少数类的识别效果。此外还使用混淆矩阵展示错分的方向与数量，"
        "以便分析哪些类别之间容易混淆。"))

A(("h2", "2.6　对比方法"))
A(("h3", "2.6.1　HOG + 支持向量机"))
A(("p", "方向梯度直方图（HOG）把图像划分为若干单元格，统计每个单元格内梯度方向的分布，再对相邻单元格做块归一化并拼接[11]。"
        "它刻画的是局部边缘的方向与强度，对光照变化不敏感，是行人检测等任务的经典特征。本文在 96×96 图像上取 9 个方向、"
        "12×12 像素的单元格、2×2 的块，得到 1764 维特征，标准化后用线性 SVM 分类。"))
A(("h3", "2.6.2　形状特征 + 支持向量机"))
A(("p", "针对示功图这类闭合轮廓，可以提取更具物理意义的形状特征：轮廓面积、周长、外接矩形宽高与长宽比、矩形度、"
        "圆形度、凸度、载荷跨度、位移跨度、载荷位移比、质心位置以及 7 个 Hu 不变矩，共 21 维。"
        "这些特征与工程上“看图形”的经验相对应，再送入 RBF 核 SVM[12]，代表传统的“特征工程 + 浅层分类器”范式。"))
A(("h3", "2.6.3　ResNet18"))
A(("p", "ResNet18 通过残差连接缓解深层网络的梯度消失问题，是应用最广的骨干网络之一[13]。本文把它的第一层卷积改为单通道输入，"
        "从头训练 10 轮，作为“更深、更大容量”模型的代表，用来检验增加网络深度是否还能带来精度收益。"))
A(("p", "此外还设置了“原始像素 + PCA(64) + RBF SVM”作为最朴素的基线：把 48×48 的灰度图展平成 2304 维向量，"
        "用主成分分析降到 64 维后分类，用以说明在类间差异明显的图像上，即使不做任何特征设计也能取得不错的效果。"))
